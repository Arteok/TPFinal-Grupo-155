CREATE TABLE profesional (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    telefono VARCHAR(50)
);

CREATE TABLE agenda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    profesional_id BIGINT NOT NULL UNIQUE,
    FOREIGN KEY (profesional_id) REFERENCES profesional(id) ON DELETE CASCADE
);

CREATE TABLE agenda_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia_semana VARCHAR(20) NOT NULL CHECK (dia_semana IN ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')), -- Ej: 'MONDAY', 'TUESDAY'
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    motivo VARCHAR(255),
    agenda_id BIGINT NOT NULL,
    FOREIGN KEY (agenda_id) REFERENCES agenda(id) ON DELETE CASCADE
);

CREATE TABLE excepcion_agenda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    motivo VARCHAR(255),
    agenda_id BIGINT NOT NULL,
    FOREIGN KEY (agenda_id) REFERENCES agenda(id) ON DELETE CASCADE
);

CREATE TABLE turno (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora_inicio TIMESTAMP NOT NULL,
    fecha_hora_fin TIMESTAMP NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'CONFIRMADO', 'CANCELADO')), -- ENUM: PENDIENTE, CONFIRMADO, CANCELADO
    paciente_nombre VARCHAR(150) NOT NULL,
    paciente_telefono VARCHAR(50) NOT NULL,
    agenda_id BIGINT NOT NULL,
    FOREIGN KEY (agenda_id) REFERENCES agenda(id)
);